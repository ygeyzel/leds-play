# --- Meteor "danger budget" difficulty system ---------------------------
# Each wave of meteors is generated by spending a difficulty budget that
# grows with play time (turns), independent of the player's score. Every meteor trait (size, zigzag, speed)
# has a danger cost; a wave keeps spawning meteors until the remaining
# budget can't afford even the cheapest one. Choosing an expensive trait
# on one meteor leaves less budget for additional meteors that wave.
# These weights are starting points, tune freely.
BASE_METEOR_DANGER = 5      # cost of a plain, slow (speed 1), small meteor
BIG_METEOR_DANGER = 10      # extra cost for a 2x2 meteor instead of 1x1
ZIG_ZAG_DANGER = 8          # extra cost for zigzag movement
SPEED_DANGER_PER_LEVEL = 6  # extra cost per +1 speed above the base of 1

MAX_METEOR_SPEED = 3
MAX_METEORS_ON_SCREEN = 10

BASE_DANGER_BUDGET = 10
DANGER_BUDGET_SECONDS_PER_POINT = 10  # +1 budget for every 10 seconds played
DANGER_BUDGET_TURNS_PER_POINT = round(DANGER_BUDGET_SECONDS_PER_POINT / TURN_INTERVAL)


# --- Aid package system -------------------------------------------------
# The game level comes from the score. Each level plans a few aid packages
# at random scores inside that level's score range: MIN..MAX per level,
# plus one extra every EXTRA_AID_EVERY_N_LEVELS levels. So packages per
# level stay roughly constant no matter how many meteors get shot.
SCORE_PER_LEVEL = 100
MIN_AID_PER_LEVEL = 1
MAX_AID_PER_LEVEL = 2
EXTRA_AID_EVERY_N_LEVELS = 3

# The score of the meteor that dropped a package picks the tier its type
# is drawn from: (minimum meteor score, aid types that can drop there).
# Sorted ascending. Tougher meteors (big / zig-zag / fast) drop rarer ones.
AID_TYPES_BY_SCORE = [
    (0, ['extra shot', 'city hp']),
    (15, ['slawer meteors', 'extra canon']),
    (25, ['splinter shot', 'dubel score']),
]

# Timed aid effects, in seconds of play (converted to turns with
